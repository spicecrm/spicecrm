namespace SpiceCRM\modules\Employees;

use SpiceCRM\data\BeanFactory;
use SpiceCRM\includes\SugarObjects\templates\person\Person;

class Employee extends Person
{

    public function __construct()
    {
        parent::__construct();
        $this->emailAddress = BeanFactory::getBean('EmailAddresses');
    }

    /**
     * enrich with primary orgunit data
     * @param $id
     * @param $encode
     * @param $deleted
     * @param $relationships
     * @return Person|null
     */
    public function retrieve($id = -1, $encode = true, $deleted = true, $relationships = true)
    {
        $bean = parent::retrieve($id, $encode, $deleted, $relationships); // TODO: Change the autogenerated stub
        if ($bean) {
            $bean->populateOrgUnitData();
        }
        return $bean;
    }


    /**
     * make some values directly available in the list view for ACLs
     * @return void
     */
    public function retrieveListDetails()
    {
        parent::retrieveListDetails();
        $this->populateOrgUnitData();
    }

    /**
     * make some values directly available in the detail view for ACLs
     * @return void
     */
    public function retrieveViewDetails()
    {
        parent::retrieveViewDetails();
        $this->populateOrgUnitData();

    }

    /**
     * set non db fields orgunit_id and orgunit_name
     * @return void
     */
    public function populateOrgUnitData()
    {
        $primaryOrgUnit = $this->getPrimaryOrgUnit();
        if ($primaryOrgUnit) {
            $this->orgunit_id = $primaryOrgUnit->id;
            $this->orgunit_name = $primaryOrgUnit->name;
        }
    }

    /**
     * return the primary orgunit object for the employee
     * @return false|mixed
     */
    public function getPrimaryOrgUnit()
    {
        $orgunit = $this->get_linked_beans('orgunitprimary');
        if (count($orgunit) > 0) {
            return $orgunit[0];
        }

        // BWC fallback check employees.orgunit_id
        if (!empty($this->orgunit_id)) {
            $orgunit = BeanFactory::getBean('OrgUnits', $this->orgunit_id);
            return $orgunit;
        }

        return false;
    }

    /**
     * return the user assigned of the primary orgunit object for the employee
     * @return false|mixed
     */
    public function getManagerPrimaryOrgUnit()
    {
        $orgunit = $this->getPrimaryOrgUnit();
        if ($orgunit) {
            $manager = BeanFactory::getBean('Users', $orgunit->assigned_user_id);
            if ($manager) {
                return $manager;
            }
        }
        return false;
    }


}
