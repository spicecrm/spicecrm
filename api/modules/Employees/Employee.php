namespace SpiceCRM\modules\Employees;

use SpiceCRM\includes\SpiceBeans\BeanFactory;
use SpiceCRM\includes\SugarObjects\templates\person\Person;
use SpiceCRM\includes\TimeDate;
use DateTime;

class Employee extends Person {

	public function __construct() {
		parent::__construct();
		$this->emailAddress = BeanFactory::getBean('EmailAddresses');
	}

    public function retrieveViewDetails()
    {
        parent::retrieveViewDetails(); // TODO: Change the autogenerated stub
        // get primary orgunit
        $primaryOrgUnit = $this->getPrimaryOrgUnit();
        if($primaryOrgUnit){
            $this->orgunit_id = $primaryOrgUnit->id;
            $this->orgunit_name = $primaryOrgUnit->name;
        }
    }

    /**
     * return the primary orgunit object for the employee
     * @return false|mixed
     */
    public function getPrimaryOrgUnit(){

        $orgUnitId = $this->db->getOne("SELECT orgunit_id FROM orgunits_beans WHERE bean_id = '$this->id' AND is_primary = 1 AND deleted != 1");

        if($orgUnitId){
            return BeanFactory::getBean('OrgUnits', $orgUnitId);
        }

        // BWC fallback check employees.orgunit_id
        if(!empty($this->orgunit_id)){
            $orgunit = BeanFactory::getBean('OrgUnits', $this->orgunit_id);
            return $orgunit;
        }

        return false;
    }

    /**
     * return the user assigned of the primary orgunit object for the employee
     * @return false|mixed
     */
    public function getManagerPrimaryOrgUnit(){
        $orgunit = $this->getPrimaryOrgUnit();
        if($orgunit){
            $manager = BeanFactory::getBean('Users', $orgunit->assigned_user_id);
            if($manager){
                return $manager;
            }
        }
        return false;
    }

    /**
     * checks absences for the employee for the given date and returns true if the user is absent
     *
     * @param $date
     * @return void
     */
    public function isAbsent(DateTime $date, $statuses = ['created', 'submitted', 'approved']){

        $user = BeanFactory::getBean('Users')->retrieve_by_string_fields(['parent_id' => $this->id]);
        if($user){
            $checkDate = $date->format(TimeDate::DB_DATE_FORMAT);
            $statusFilter = "'" . implode("','", $statuses) . "'";
            $record = $this->db->fetchOne("SELECT id FROM userabsences WHERE deleted = 0 AND assigned_user_id = '$user->id' AND date_start <= '$checkDate' AND date_end >= '$checkDate' AND status IN ($statusFilter)");
            if($record){
                return true;
            }
        }

        return false;
    }

}
